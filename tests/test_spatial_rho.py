def test_constant_rho_vector_equals_scalar(record):
    S = c2.setup(_blob_mask(), 3, 2 * np.pi, np.pi, Kr=4)
    b = np.random.default_rng(0).normal(size=9) * 0.3
    r = np.zeros(16); r[0] = 0.7
    e1 = float(np.abs(c2.galerkin_rhs(b, 0.1, r, 1.0) - c2.galerkin_rhs(b, 0.1, 0.7, 1.0)).max())
    e2 = float(np.abs(c2.galerkin_rhs(torch.tensor(b), 0.1, torch.tensor(r), 1.0).numpy()
                      - c2.galerkin_rhs(b, 0.1, r, 1.0)).max())
    record(numpy_err=e1, torch_err=e2)
    assert max(e1, e2) < 1e-12


def test_rho_term_is_land_projection_of_pointwise_product(record):
    """G^-1 E(r) b == L2(Omega) projection of rho(x,y) u(x,y): the rho_{kl,pq} coupling."""
    S = c2.setup(_blob_mask(), 3, 2 * np.pi, np.pi, Kr=4)
    rng = np.random.default_rng(1)
    b, r = rng.normal(size=9) * 0.3, rng.normal(size=16) * 0.2
    u = b @ S["phi"].T
    lin = c2.galerkin_rhs(b, 0.0, r, 0.0)
    ref = c2.field_to_coeffs(c2.rho_field(r) * u)
    # the coupling matrix is not diagonal for a non-constant rho
    Rm = np.einsum("amj,m->aj", S["A_rho"], r)
    off = float(np.abs(Rm - np.diag(np.diag(Rm))).max())
    # pointwise residual helper uses the same rho(x, y)
    xs = S["xy"][:50]
    gk.set_basis("cosine2d")
    try:
        pde = gk.full_pde_rhs_on_grid(b, xs, 0.0, r, 0.0)
    finally:
        gk.set_basis("fourier")
    pw = float(np.abs(pde - c2.rho_field(r, xs) * c2.reconstruct(b, xs)).max())
    err = float(np.abs(lin - ref).max())
    record(projection_err=err, max_offdiag=off, pointwise_err=pw)
    assert err < 1e-12 and off > 1e-3 and pw < 1e-12


def test_fit_recovers_spatial_rho(record):
    """Data generated by the spatial-rho Galerkin ODE -> the joint fit recovers r, beta."""
    gk.set_basis("cosine2d")
    try:
        S = c2.setup(_blob_mask(), 3, 2 * np.pi, np.pi, Kr=2)
        r_true = np.array([0.30, 0.08, -0.06, 0.04]); beta = 0.5
        rng = np.random.default_rng(2)
        traj = []
        for _ in range(6):
            a = np.zeros(9); a[0] = 0.1 + 0.2 * rng.random(); a[1:] = 0.03 * rng.normal(size=8)
            for _t in range(30):
                traj.append(a)
                a = gk.rk4_step(a, 0.5, 0.0, r_true, beta, substeps=8)
        A = np.array(traj).reshape(6, 30, 9)
        an, anp = A[:, :-1].reshape(-1, 9), A[:, 1:].reshape(-1, 9)
        f = c2.fit_spatial_rho(an, anp, 0.5, np.ones(9) * 100, np.r_[0.2, 0, 0, 0], 1e-6, 0.3,
                               lam_smooth=0.0, fit_D=False)
        err = float(np.abs(np.array(f["r"]) - r_true).max())
        record(r_err=err, beta_err=abs(f["beta"] - beta), loss=f["loss"])
        assert err < 1e-4 and abs(f["beta"] - beta) < 1e-4
    finally:
        gk.set_basis("fourier")


def test_hinge_pde_loss():
    an = torch.randn(4, 5) * 0.1
    ah = an + 0.01 * torch.randn(4, 5)
    xc = gk.uniform_grid(16)
    s = torch.ones(5)
    Lf, Lg = losses.pde_losses(an, ah, 0.1, (0.1, 1.0, 1.0), s, 1.0, xc)
    Hf, Hg = losses.pde_losses(an, ah, 0.1, (0.1, 1.0, 1.0), s, 1.0, xc, hinge_tol=1e6)
    Tf, Tg = losses.pde_losses(an, ah, 0.1, (0.1, 1.0, 1.0), s, 1.0, xc, hinge_tol=1e-30)
    assert float(Hf) == 0 and float(Hg) == 0 and abs(float(Tf) - float(Lf)) < 1e-12 and float(Lf) > 0
