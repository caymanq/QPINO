"""M = 4 (9 real coefficients, 9 qubits) extension of the Phase-12 checks:
conjugate symmetry, explicit vs convolution vs spectral projection, the full-residual order,
the M=4 coupling graph, the mirrored (even) boundary, and torch == PennyLane at 9 qubits."""
import numpy as np
import torch

from src import fisher_kpp as fk
from src import galerkin as gk
from src import losses
from src import pennylane_circuits as plc
from src import preprocessing as pp
from src.custom_ansatz import get_graph
from src.qpino import QPINO, Standardizer

torch.set_default_dtype(torch.float64)
PH = (0.1, 1.0, 1.0)
A0_M4 = np.array([0.25, 0.06, -0.03, 0.04, 0.02, 0.015, -0.01, 0.008, 0.005])


def test_m4_conjugate_symmetry(record):
    rng = np.random.default_rng(0)
    a = rng.normal(size=(20, 9)) * 0.2
    ac = gk.to_complex_modes(a)                      # k = -4..4
    f = gk.galerkin_rhs_complex(ac, *PH)
    sym = np.abs(f[:, ::-1] - f.conj()).max()        # f_{-k} = conj(f_k)
    roundtrip = np.abs(gk.from_complex_modes(ac) - a).max()
    t = np.linspace(0, 4, 41)
    # integrate the 9 complex modes as an unconstrained complex ODE and check conj symmetry persists
    from scipy.integrate import solve_ivp
    y0 = gk.to_complex_modes(A0_M4)
    sol = solve_ivp(lambda tt, y: gk.galerkin_rhs_complex(y, *PH), (0, 4), y0.astype(complex),
                    t_eval=t, rtol=1e-11, atol=1e-13)
    drift = np.abs(sol.y[::-1].T - sol.y.T.conj()).max()
    record(rhs_symmetry_err=sym, roundtrip_err=roundtrip, integrated_drift=drift)
    assert sym < 1e-14 and roundtrip == 0 and drift < 1e-10


def test_m4_explicit_vs_convolution_vs_projection(record):
    rng = np.random.default_rng(1)
    a = rng.normal(size=(50, 9)) * 0.3
    e_conv = np.abs(gk.galerkin_rhs_m4_explicit(a, *PH) - gk.galerkin_rhs_conv(a, *PH)).max()
    e_proj = np.abs(gk.galerkin_rhs_m4_explicit(a, *PH) - gk.galerkin_rhs_by_projection(a, *PH, N=64)).max()
    a2 = rng.normal(size=(50, 5)) * 0.3                # general-M code reproduces the M=2 equations
    e_m2 = np.abs(gk.galerkin_rhs_m2_explicit(a2, *PH) - gk.galerkin_rhs_conv(a2, *PH)).max()
    # M=4 embedding of an M=2 state: the k<=2 part of the M=4 RHS differs from M=2 only by
    # the newly resolved |k|=3,4 modes generated by u^2
    at = torch.tensor(a, requires_grad=True)
    gk.galerkin_rhs(at, *PH).sum().backward()           # differentiable
    record(explicit_vs_conv=e_conv, explicit_vs_projection=e_proj, m2_explicit_vs_general=e_m2)
    assert e_conv < 1e-13 and e_proj < 1e-12 and e_m2 < 1e-13 and at.grad is not None


def test_m4_coupling_graph(record):
    E = get_graph("structured", 9)
    missing = [p for p in __import__("itertools").combinations(range(9), 2) if p not in E]
    record(n_edges=len(E), n_pairs=36, missing=str(missing), triad_edges=len(get_graph("triad", 9)))
    # b_k c_k products appear only through a_k^2 -> mode 2k, which is resolved only for k <= 2
    assert len(E) == 34 and missing == [(5, 6), (7, 8)]
    assert len(get_graph("structured", 5)) == 9


def test_m4_projected_residual_order(record):
    out = {}
    for sch, oe in [("forward", 1.0), ("trapezoid", 2.0), ("midpoint", 2.0)]:
        rms = []
        for dt in [0.1, 0.05, 0.025, 0.0125]:
            t = np.arange(0, 1.0 + 1e-12, dt)
            A = torch.tensor(gk.integrate_galerkin(A0_M4, t, *PH))
            R = losses.galerkin_residual(A[:-1], A[1:], dt, *PH, scheme=sch)
            rms.append(float(R.pow(2).mean().sqrt()))
        order = np.log2(rms[-2] / rms[-1])
        out[f"{sch}_order"] = order
        assert abs(order - oe) < 0.25
    record(**out)


def test_m4_full_residual(record):
    """Full PDE residual (trapezoid) of an accurate full solution projected to M=4 is much
    smaller than at M=2 and plateaus at the |k|>4 unresolved level as dt -> 0."""
    N = 128
    x = 2 * np.pi * np.arange(N) / N
    u0 = 0.25 + 0.12 * np.cos(x) + 0.08 * np.sin(2 * x)
    xc = gk.uniform_grid(128)
    r = {}
    for Mk in (2, 4):
        rr = []
        for dt in [0.05, 0.025, 0.0125]:
            t = np.arange(0, 1.0 + 1e-12, dt)
            A = torch.tensor(gk.field_to_coeffs(fk.solve(u0, t, *PH, rtol=1e-12, atol=1e-14), x, Mk))
            R = losses.full_pde_residual(A[:-1], A[1:], dt, *PH, xc, scheme="trapezoid")
            rr.append(float(R.pow(2).mean().sqrt()))
        r[Mk] = rr
    record(full_rms_M2=r[2], full_rms_M4=r[4], ratio_M2_over_M4=r[2][-1] / r[4][-1])
    assert r[4][-1] < 0.1 * r[2][-1]
    assert abs(r[4][-1] - r[4][-2]) / r[4][-1] < 0.2   # plateau (truncation-limited)


def test_mirror_boundary_even(record):
    rng = np.random.default_rng(2)
    u = rng.random((3, 32)) + np.linspace(0, 2, 32)        # strong end-to-end ramp
    um = pp.mirror_extend(u)
    xm = gk.uniform_grid(64, 0.5)
    a = gk.field_to_coeffs(um, xm, 4)
    im = np.abs(a[:, 2::2]).max()
    # the Galerkin dynamics preserve evenness (Im a_k stays exactly 0)
    i = np.arange(9)
    cos_only = np.where((i == 0) | (i % 2 == 1), 1.0, 0.0) * np.abs(a[0]) * 0.1
    traj_even = gk.integrate_galerkin(cos_only, np.linspace(0, 2, 5), *PH)
    jump = np.abs(um[:, -1] - um[:, 0]).max()
    record(max_im=im, mirror_wrap_jump=jump, even_traj_max_im=np.abs(traj_even[:, 2::2]).max())
    assert im < 1e-14 and jump == 0 and np.abs(traj_even[:, 2::2]).max() < 1e-14 and traj_even.shape == (5, 9)


def test_torch_matches_pennylane_9_qubits(record):
    norm = Standardizer(np.zeros(9), np.ones(9), np.ones(9))
    a = torch.randn(2, 9) * 0.5
    q = plc.make_qnode(n=9)
    errs = {}
    for R in (1, 2):
        m = QPINO(norm, n=9, reupload=R, seed=11, alpha0=1.2)
        mt = m.measure(a, 0.6).detach().numpy()
        hps = [(l.h.detach().numpy(), l.g.detach().numpy(), l.J.detach().numpy()) for l in m.layers]
        ang = (m.alphas * a).detach().numpy()
        pl = np.array([q([ang[i]] * R, hps, m.layers[0].edges, float(m.tau(0.6))) for i in range(2)])
        errs[f"R{R}"] = float(np.abs(mt - pl).max())
    m = QPINO(norm, n=9, seed=12, evolution="trotter", trotter_L=2)
    mt = m.measure(a, 0.6).detach().numpy()
    l = m.layers[0]
    ang = (m.alphas * a).detach().numpy()
    pl = np.array([q([ang[i]], [(l.h.detach().numpy(), l.g.detach().numpy(), l.J.detach().numpy())],
                     l.edges, float(m.tau(0.6)), "trotter", 2) for i in range(2)])
    errs["trotter2"] = float(np.abs(mt - pl).max())
    record(n_features=int(mt.shape[1]), **errs)
    assert mt.shape[1] == 9 + 36 and max(errs.values()) < 1e-10


def test_eigh_expm_matches_matrix_exp(record):
    """The fast eigh-based exact exponential used for 9-qubit training gives the same unitary
    and gradients as torch.linalg.matrix_exp (incl. a fully degenerate spectrum)."""
    from src.custom_ansatz import HamiltonianAnsatz
    out = {}
    W = torch.randn(512, 512, dtype=torch.complex128, generator=torch.Generator().manual_seed(0))
    A = HamiltonianAnsatz(get_graph("structured", 9), n=9, seed=1)
    res = {}
    for meth in ("exact", "exact_eigh"):
        A.zero_grad()
        c = torch.tensor(1.3, requires_grad=True)
        U = A.unitary(c * 0.7, meth)
        ((U * W).real.sum() + (U.abs() ** 2 * W.real).sum()).backward()
        res[meth] = (U.detach(), [p.grad.clone() for p in A.parameters()], float(c.grad))
    a, b = res["exact"], res["exact_eigh"]
    out["U_err"] = float((a[0] - b[0]).abs().max())
    out["grad_rel_err"] = max(float((x - y).abs().max() / x.abs().max()) for x, y in zip(a[1], b[1]))
    out["tau_grad_rel_err"] = abs(a[2] - b[2]) / abs(a[2])
    D = HamiltonianAnsatz([], n=5, seed=1)
    with torch.no_grad():
        D.h.fill_(0.3); D.g.fill_(0.0)
    G = {}
    for meth in ("exact", "exact_eigh"):
        D.zero_grad()
        (D.unitary(torch.tensor(0.9), meth) * torch.arange(1024.).reshape(32, 32)).real.sum().backward()
        G[meth] = [p.grad.clone() for p in D.parameters() if p.grad is not None]
    out["degenerate_grad_rel_err"] = max(float((x - y).abs().max() / x.abs().max()) for x, y in zip(G["exact"], G["exact_eigh"]))
    record(**out)
    assert out["U_err"] < 1e-12 and out["grad_rel_err"] < 1e-10 and out["tau_grad_rel_err"] < 1e-10
    assert out["degenerate_grad_rel_err"] < 1e-9
