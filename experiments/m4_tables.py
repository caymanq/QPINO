"""Aggregate results/metrics/m4/*.json -> results/metrics/m4_summary.json + docs/results_tables_m4.md."""
import glob
import json
import os
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MET = os.path.join(ROOT, "results", "metrics")
runs = defaultdict(list)
for f in glob.glob(os.path.join(MET, "m4", "*_s[0-9].json")):
    d = json.load(open(f))
    m = d["meta"]
    runs[(m["regime"], m["M"], m["boundary"], m["model"], m["lambda_pde"], m["R"])].append(d["result"])
base = {os.path.basename(f)[10:-5]: json.load(open(f)) for f in glob.glob(os.path.join(MET, "m4", "baselines_*.json"))}
trunc = json.load(open(os.path.join(MET, "m4_truncation.json")))
old_c = json.load(open(os.path.join(MET, "covid_results.json")))
old_s = json.load(open(os.path.join(MET, "synthetic_results.json")))


def agg(rows):
    out = {"n_seeds": len(rows)}
    for k, v in rows[0].items():
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            a = np.array([r[k] for r in rows], float)
            out[k] = dict(mean=float(a.mean()), std=float(a.std()))
    return out


summary = {"|".join(map(str, k)): agg(v) for k, v in sorted(runs.items())}
json.dump(dict(runs=summary, baselines={k: v["results"] for k, v in base.items()},
               fits={k: v["meta"].get("fit") for k, v in base.items()}),
          open(os.path.join(MET, "m4_summary.json"), "w"), indent=2, default=float)


def g(key, metric, fmt="{:.3f}", std=True):
    s = summary.get(key)
    if not s or metric not in s:
        return "n/a"
    m, sd = s[metric]["mean"], s[metric]["std"]
    return (fmt.format(m) + (" ± " + fmt.format(sd) if std and s["n_seeds"] > 1 else "")) + \
        ("" if s["n_seeds"] == 3 else f" (n={s['n_seeds']})")


def ob(name, metric, src, fmt="{:.3f}"):
    s = src["summary"].get(name)
    if not s:
        return "n/a"
    m = s[metric]
    return fmt.format(m["mean"]) + (" ± " + fmt.format(m["std"]) if m["std"] > 0 else "")


