def prev_best(model):
    """Lowest July rollout RMSE of the same model letter in any earlier (complex-Fourier) config."""
    cands = []
    if model in old_c["summary"]:
        m_ = old_c["summary"][model]
        cands.append((m_["field_rmse_per100k_rollout"]["mean"], m_["field_rmse_per100k_rollout"]["std"],
                      m_["rel_l2_increment"]["mean"], "M2 periodic λ0.1"))
    for k, v in summary.items():
        reg, M_, b, mdl, lam, R = k.split("|")
        if reg == "covid" and b in ("periodic", "mirror") and mdl == model and "field_rmse_per100k_rollout" in v:
            cands.append((v["field_rmse_per100k_rollout"]["mean"], v["field_rmse_per100k_rollout"]["std"],
                          v["rel_l2_increment"]["mean"], f"M{M_} {b} λ{float(lam):g} R{R}"))
    for cfg, v in base.items():
        if cfg.startswith("covid_") and not cfg.endswith("cosine") and model in v["results"]:
            r = v["results"][model]
            cands.append((r["field_rmse_per100k_rollout"], 0.0, r["rel_l2_increment"], cfg[6:].replace("_", " ")))
    return min(cands) if cands else None


